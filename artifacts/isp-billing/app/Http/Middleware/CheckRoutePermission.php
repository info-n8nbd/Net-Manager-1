    public function handle(Request $request, Closure $next): Response
    {
        if (!auth()->check()) {
            return redirect()->route('login');
        }

        $user = auth()->user();

        if ($user->user_type === 'super_admin' || $user->hasRole('Super Admin')) {
            return $next($request);
        }

        $routeName = $request->route()->getName();

        if (!$routeName || !isset(self::$routeMenuMap[$routeName])) {
            return $next($request);
        }

        $menuKey = self::$routeMenuMap[$routeName];

        // Support pipe-separated OR keys: 'mac_reseller.list|bw_reseller.list'
        $menuKeys = explode('|', $menuKey);
        $canAccess = false;
        foreach ($menuKeys as $mk) {
            $parts = explode('.', trim($mk), 2);
            $mainMenu = $parts[0];
            $subMenu = $parts[1] ?? null;
            if (MenuPermissionService::canAccessMenu($user, $mainMenu, $subMenu)) {
                $canAccess = true;
                break;
            }
        }

        if ($canAccess) {
            return $next($request);
        }

        if ($request->ajax() || $request->wantsJson()) {
            return response()->json(['error' => 'You do not have permission to access this feature.'], 403);
        }

        abort(403, 'You do not have permission to access this feature.');
    }
